#!/usr/bin/env npx tsx
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { parseConfig } from "../src/config";

/**
 * Compiles the instance (YAML + legal texts) into
 * src/generated/config.ts — the status-service `gen` pattern. Instance
 * data is never compiled-in by hand; the gates run gen first and a
 * validation failure fails the gate. Real instance values live in the
 * PRIVATE instance repo; this repo's checked-in example keeps CI green.
 */

const configArg = process.env.CONFIG;
const candidates = [configArg, "config/cla.yaml", "config/cla.example.yaml"].filter((p): p is string => Boolean(p));
const configPath = candidates.find((p) => existsSync(p));

if (!configPath) {
  console.error("gen: no instance config found (CONFIG env, config/cla.yaml, or config/cla.example.yaml)");
  process.exit(1);
}

const yamlText = readFileSync(configPath, "utf8");
const baseDir = dirname(resolve(configPath));
const readLegal = (rel: string): Promise<string> => {
  const p = resolve(baseDir, rel);
  if (!p.startsWith(baseDir)) return Promise.reject(new Error("legal path escapes config dir"));
  return Promise.resolve(readFileSync(p, "utf8"));
};

const result = await parseConfig(yamlText, readLegal);
if ("errors" in result) {
  console.error(`gen: ${configPath} is invalid (fail-closed):`);
  for (const e of result.errors) console.error(`  - ${e.path}: ${e.message}`);
  process.exit(1);
}

const emit = `// GENERATED by scripts/gen.ts from ${configPath} — never hand-edit.
import type { AppConfig } from "../config";

export const GENERATED_CONFIG: AppConfig = ${JSON.stringify(result.config, null, 2)};
`;

mkdirSync("src/generated", { recursive: true });
writeFileSync("src/generated/config.ts", emit);
console.log(`gen: wrote src/generated/config.ts from ${configPath}`);
